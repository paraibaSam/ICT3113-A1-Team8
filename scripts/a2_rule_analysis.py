"""Assignment 2, Step 2: escalation-rule design on the TUNING set only.

Reads A1 per-ticket records for the small model (default gemma3:4b) and the large model
(default qwen2.5:7b), keeps ONLY rows whose split is 'tuning' in golden-set/a2_split.csv,
and reports:
  1. small-model accuracy by TRUE category (recall) and by PREDICTED category (precision:
     "when it says X, how often is it right" - the only thing a rule can use at run time)
  2. where the small model's wrong answers go (confusion on tuning)
  3. ticket length vs small-model errors (for a length rule)
  4. offline simulation of category-based rules: escalate when the small model's predicted
     category is in set S; final answer = large model's A1 answer for escalated tickets.
     Every one of the 2^7 sets is simulated; the Pareto frontier (min escalation for a given
     accuracy) is listed, plus named candidate settings.
  5. estimated mean latency per rule, from A1 accuracy-run round-trip times (sequential,
     one model loaded): small_rt + escalated * large_rt.  An estimate only; the speed test
     is what counts.

Test rows are never read into the analysis.

Usage: python3 scripts/a2_rule_analysis.py [--small gemma3_4b] [--large qwen2.5_7b]
Writes results/a2/rule_design/tuning_analysis.md
"""
import argparse
import csv
import itertools
import os
import statistics as st

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CATS = [
    "Credit reporting",
    "Debt collection",
    "Mortgage",
    "Credit card",
    "Bank account or service",
    "Consumer loan",
    "Money transfer or service",
]
SHORT = {"Credit reporting": "CR", "Debt collection": "DC", "Mortgage": "MO", "Credit card": "CC",
         "Bank account or service": "BA", "Consumer loan": "CL", "Money transfer or service": "MT"}

ap = argparse.ArgumentParser()
ap.add_argument("--small", default="gemma3_4b")
ap.add_argument("--large", default="qwen2.5_7b")
ap.add_argument("--out", default=os.path.join(ROOT, "results", "a2", "rule_design", "tuning_analysis.md"))
args = ap.parse_args()


def read(p):
    with open(p, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


split = {r["row_id"]: r["split"] for r in read(os.path.join(ROOT, "golden-set", "a2_split.csv"))}
tuning_ids = {k for k, v in split.items() if v == "tuning"}
narr = {r["row_id"]: r["narrative"] for r in read(os.path.join(ROOT, "golden-set", "a2_tuning.csv"))}
assert set(narr) == tuning_ids


def load(model_dir):
    rows = read(os.path.join(ROOT, "results", model_dir, "per_ticket_results.csv"))
    return {r["row_id"]: r for r in rows if r["row_id"] in tuning_ids}  # TUNING ONLY


S = load(args.small)
L = load(args.large)
assert set(S) == tuning_ids == set(L), "records must cover every tuning row"
ids = sorted(tuning_ids, key=int)
N = len(ids)
gold = {i: S[i]["final_label"] for i in ids}
sp = {i: S[i]["predicted_label"] if S[i]["predicted_label"] in CATS else "(err)" for i in ids}
lp = {i: L[i]["predicted_label"] if L[i]["predicted_label"] in CATS else "(err)" for i in ids}
s_rt = {i: int(S[i]["round_trip_ms"]) for i in ids}
l_rt = {i: int(L[i]["round_trip_ms"]) for i in ids}

out = []
w = out.append
pct = lambda c, n: f"{100*c/n:.1f}%" if n else "n/a"

w(f"# Escalation-rule design: tuning set only ({N} tickets)\n")
w(f"Generated by `scripts/a2_rule_analysis.py`. Small model **{args.small}**, large model **{args.large}**. "
  "Source: A1 `results/<model>/per_ticket_results.csv`, restricted to the tuning rows of `golden-set/a2_split.csv`. "
  "**No test-set rows are read.**\n")

s_ok = sum(sp[i] == gold[i] for i in ids)
l_ok = sum(lp[i] == gold[i] for i in ids)
w(f"- {args.small} alone: **{s_ok}/{N} ({pct(s_ok, N)})**, mean A1 round trip {st.mean(s_rt.values())/1000:.2f} s, median {st.median(s_rt.values())/1000:.2f} s")
w(f"- {args.large} alone: **{l_ok}/{N} ({pct(l_ok, N)})**, mean A1 round trip {st.mean(l_rt.values())/1000:.2f} s, median {st.median(l_rt.values())/1000:.2f} s\n")

# ---- 1. recall and precision
w("## 1. Which categories the small model gets right\n")
w("*By true category* (recall) is what the per-category limit is judged on. *By predicted category* (precision) is what a rule can use, because the true category is unknown when a ticket arrives.\n")
w(f"| Category | True n | {args.small} right (recall) | {args.large} right | Times {args.small} predicted it | Right when predicted (precision) | Wrong answers let through if accepted |")
w("|---|---|---|---|---|---|---|")
prec = {}
for c in CATS:
    tn = [i for i in ids if gold[i] == c]
    pn = [i for i in ids if sp[i] == c]
    rc = sum(sp[i] == c for i in tn)
    lc = sum(lp[i] == c for i in tn)
    pc = sum(gold[i] == c for i in pn)
    prec[c] = (pc, len(pn))
    w(f"| {c} | {len(tn)} | {rc}/{len(tn)} ({pct(rc, len(tn))}) | {lc}/{len(tn)} ({pct(lc, len(tn))}) | {len(pn)} | {pc}/{len(pn)} ({pct(pc, len(pn))}) | {len(pn)-pc} |")
errs = [i for i in ids if sp[i] == "(err)"]
w(f"\nUnparseable or error answers from {args.small} on tuning: {len(errs)}.\n")

# ---- 2. confusion
w(f"## 2. Where {args.small}'s wrong answers go (tuning confusion, rows = true, cols = predicted)\n")
cols = CATS + ["(err)"]
w("| True \\ Pred | " + " | ".join(SHORT.get(c, "Err") for c in cols) + " | Wrong |")
w("|---|" + "---|" * (len(cols) + 1))
for a in CATS:
    row = [sum(1 for i in ids if gold[i] == a and sp[i] == p) for p in cols]
    wrong = sum(row) - row[CATS.index(a)]
    w(f"| {a} | " + " | ".join(f"**{v}**" if p == a else (str(v) if v else "·") for v, p in zip(row, cols)) + f" | {wrong} |")
w("\nKey: " + "; ".join(f"{v} = {k}" for k, v in SHORT.items()) + "\n")

pairs = {}
for i in ids:
    if sp[i] != gold[i]:
        pairs[(gold[i], sp[i])] = pairs.get((gold[i], sp[i]), 0) + 1
w("Most common mistakes (true → predicted): " + "; ".join(f"{a} → {b} ×{n}" for (a, b), n in sorted(pairs.items(), key=lambda x: -x[1])[:8]) + "\n")

# does the large model fix them?
fix = sum(1 for i in ids if sp[i] != gold[i] and lp[i] == gold[i])
brk = sum(1 for i in ids if sp[i] == gold[i] and lp[i] != gold[i])
both = sum(1 for i in ids if sp[i] != gold[i] and lp[i] != gold[i])
w(f"Of {args.small}'s {N-s_ok} wrong answers, **{args.large} gets {fix} right** and {both} are wrong for both models (no rule can fix those). "
  f"On the other side, {brk} tickets that {args.small} gets right are ones {args.large} gets wrong, so escalating them would *lose* accuracy.\n")

# ---- 3. length
w("## 3. Ticket length vs small-model errors (for a length rule)\n")
lens = {i: len(narr[i]) for i in ids}
qs = sorted(lens.values())
cuts = [qs[int(len(qs) * q)] for q in (0.25, 0.5, 0.75)]
bands = [(0, cuts[0]), (cuts[0], cuts[1]), (cuts[1], cuts[2]), (cuts[2], 10**9)]
w("| Length band (chars) | Tickets | " + f"{args.small} right | {args.large} right | {args.small} mean rt |")
w("|---|---|---|---|---|")
for lo, hi in bands:
    b = [i for i in ids if lo <= lens[i] < hi]
    sc = sum(sp[i] == gold[i] for i in b)
    lc = sum(lp[i] == gold[i] for i in b)
    w(f"| {lo}–{hi if hi < 10**9 else 'max'} | {len(b)} | {sc}/{len(b)} ({pct(sc, len(b))}) | {lc}/{len(b)} ({pct(lc, len(b))}) | {st.mean(s_rt[i] for i in b)/1000:.2f} s |")
w("")

# ---- 4. category-rule simulation
def simulate(esc_set):
    esc = [i for i in ids if sp[i] in esc_set]
    final = {i: (lp[i] if sp[i] in esc_set else sp[i]) for i in ids}
    ok = sum(final[i] == gold[i] for i in ids)
    acc_esc = sum(final[i] == gold[i] for i in esc)
    non = [i for i in ids if i not in set(esc)]
    acc_non = sum(final[i] == gold[i] for i in non)
    lat = st.mean(s_rt[i] + (l_rt[i] if sp[i] in esc_set else 0) for i in ids) / 1000
    percat = {c: (sum(final[i] == c for i in ids if gold[i] == c), sum(1 for i in ids if gold[i] == c)) for c in CATS}
    return dict(set=esc_set, esc=len(esc), ok=ok, acc_esc=(acc_esc, len(esc)), acc_non=(acc_non, len(non)), lat=lat, percat=percat)


# '(err)' predictions are always escalated: an unparseable answer can never be accepted.
sims = []
for k in range(len(CATS) + 1):
    for combo in itertools.combinations(CATS, k):
        sims.append(simulate(set(combo) | {"(err)"}))

large_lat = st.mean(l_rt.values()) / 1000
w("## 4. Category-based rule: simulation of all 128 escalation sets\n")
w(f"Rule: escalate when {args.small}'s *predicted* category is in the set (unparseable answers are always escalated). "
  f"Escalated tickets take {args.large}'s A1 answer. Estimated latency = mean over tickets of {args.small} rt + ({args.large} rt if escalated), from A1 accuracy-run times. "
  f"For reference, {args.large} alone ≈ {large_lat:.2f} s mean, {args.small} alone ≈ {st.mean(s_rt.values())/1000:.2f} s.\n")

# Pareto frontier: for each escalation count, best accuracy; keep only strictly improving
front = []
best = -1
for s in sorted(sims, key=lambda x: (x["esc"], -x["ok"])):
    if s["ok"] > best:
        front.append(s)
        best = s["ok"]
fmt_set = lambda s: "{" + ", ".join(SHORT[c] for c in CATS if c in s) + "}" if (s - {"(err)"}) else "{} (accept all)"


def row(s, label=""):
    pc = " ".join(f"{SHORT[c]} {s['percat'][c][0]}/{s['percat'][c][1]}" for c in CATS)
    ae, ne = s["acc_esc"], s["acc_non"]
    return (f"| {label}{fmt_set(s['set'])} | {s['esc']}/{N} ({pct(s['esc'], N)}) | {s['ok']}/{N} ({pct(s['ok'], N)}) | "
            f"{ae[0]}/{ae[1]} | {ne[0]}/{ne[1]} | {s['lat']:.2f} s | {pc} |")


hdr = "| Escalate when predicted ∈ | Escalated | Cascade accuracy | Escalated right | Accepted right | Est. mean latency | Per category (right/n) |\n|---|---|---|---|---|---|---|"
w("### Pareto frontier (most accuracy for the least escalation)\n")
w(hdr)
for s in front:
    w(row(s))
w("")

# Named candidates
named = [
    ("Accept all (small alone) ", set()),
    ("Escalate all (≈ large alone) ", set(CATS)),
    ("Weak-precision categories ", {c for c in CATS if prec[c][1] and prec[c][0] / prec[c][1] < 0.70}),
    ("Weak-precision categories ", {c for c in CATS if prec[c][1] and prec[c][0] / prec[c][1] < 0.80}),
    ("Weak-precision categories ", {c for c in CATS if prec[c][1] and prec[c][0] / prec[c][1] < 0.90}),
]
w("### Named candidates\n")
w("Weak-precision categories = categories where, on tuning, the small model's prediction is right less than X% of the time.\n")
w(hdr)
for (label, sset), thr in zip(named, ["", "", "<70% ", "<80% ", "<90% "]):
    w(row(simulate(sset | {"(err)"}), label + thr))
w("")

# ---- 5. dominated note on length rule simulation
w("## 5. Length rule (for comparison)\n")
w("Rule: tickets longer than the cut-off skip the small model and go straight to the large model (no small-model cost on those).\n")
w("| Cut-off (chars) | Sent to large | Accuracy | Est. mean latency |\n|---|---|---|---|")
for cut in cuts + [qs[int(len(qs) * 0.9)]]:
    big = [i for i in ids if lens[i] > cut]
    ok = sum((lp[i] if lens[i] > cut else sp[i]) == gold[i] for i in ids)
    lat = st.mean((l_rt[i] if lens[i] > cut else s_rt[i]) for i in ids) / 1000
    w(f"| > {cut} | {len(big)}/{N} ({pct(len(big), N)}) | {ok}/{N} ({pct(ok, N)}) | {lat:.2f} s |")
w("")

os.makedirs(os.path.dirname(args.out), exist_ok=True)
with open(args.out, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("\n".join(out))
